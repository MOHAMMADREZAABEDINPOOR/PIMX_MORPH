export function copyFor(lang: Language) {
  return (english: string, persian: string): string => {
    if (lang === "fa") return persian;
    if (lang === "en") return english;
    const index = locales.indexOf(lang);
    const exact = table.get(english)?.[index];
    if (exact) return exact;
    const paragraph = paragraphs.find(([prefix]) => english.startsWith(prefix));
    if (paragraph) return paragraph[1][index];
    const alias = legacyAliases[english];
    if (alias && TRANSLATIONS[lang]?.[alias]) return TRANSLATIONS[lang][alias];
    return english;
  };
}
